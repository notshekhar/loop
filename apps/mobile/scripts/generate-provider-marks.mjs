// The phone draws the same provider marks as the web app. Those live in
// apps/web as React DOM components (LoopProviderIcons.tsx, generated from
// models.dev, plus the Claude Code and Cursor marks in Icons.tsx); this
// re-emits them as SVG strings that react-native-svg's SvgXml renders, keyed
// by the same component names `apps/web/src/loop/providers/index.ts` uses.
//
//   node scripts/generate-provider-marks.mjs
//
// Run it after regenerating the web icons.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(dirname(fileURLToPath(import.meta.url)));
const web = join(here, "../web/src/components");
const OUT = join(here, "src/components/providerMarks.generated.ts");

/** Component name → the fill its web version gets from a class, if any. */
const SOURCES = [
  { file: "LoopProviderIcons.tsx", names: null },
  // Fixed brand colours on the web come from Tailwind classes; carried as fills.
  { file: "Icons.tsx", names: { ClaudeCodeIcon: "#D97757", CursorIcon: "currentColor" } },
];

const toSvgAttr = (jsx) =>
  jsx.replace(/\bfillRule=/g, "fill-rule=").replace(/\bclipRule=/g, "clip-rule=").replace(/\s*\{\.\.\.props\}/g, "");

const marks = {};
for (const { file, names } of SOURCES) {
  const src = readFileSync(join(web, file), "utf8");
  const re = /export const (\w+): Icon = [^]*?<svg([^]*?)>([^]*?)<\/svg>/g;
  for (const m of src.matchAll(re)) {
    const [, name, svgAttrs, body] = m;
    if (names && !(name in names)) continue;
    const viewBox = /viewBox="([^"]+)"/.exec(svgAttrs)?.[1];
    if (!viewBox) continue;
    const fill = names?.[name];
    let inner = toSvgAttr(body.trim()).replace(/\s+/g, " ");
    if (fill) inner = inner.replace(/<path /g, `<path fill="${fill}" `);
    marks[name] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="none">${inner}</svg>`;
  }
}

// iconKey → mark, read from the web's own table so the two cannot disagree.
const index = readFileSync(join(here, "../web/src/loop/providers/index.ts"), "utf8");
const table = (re) => {
  const body = re.exec(index)?.[1] ?? "";
  const out = {};
  for (const m of body.matchAll(/^\s*("?[\w-]+"?):\s*(\w+),/gm)) {
    const name = m[2];
    if (!marks[name]) throw new Error(`index.ts names ${name}, which has no mark`);
    out[m[1].replace(/"/g, "")] = name;
  }
  return out;
};
const byKey = table(/const ICONS: Record<string, Icon> = \{([^]*?)\n\};/);
const byShape = table(/const SHAPE_ICONS: Record<CustomProviderShape, Icon> = \{([^]*?)\n\};/);
if (Object.keys(byKey).length === 0) throw new Error("found no ICONS table in providers/index.ts");

const lines = Object.entries(marks).map(([name, xml]) => `  ${name}: ${JSON.stringify(xml)},`);
writeFileSync(
  OUT,
  `// GENERATED by scripts/generate-provider-marks.mjs from apps/web — do not edit.\n` +
    `// Marks paint with currentColor; the trademarks remain their owners'.\n` +
    `export const PROVIDER_MARKS: Readonly<Record<string, string>> = {\n${lines.join("\n")}\n};\n\n` +
    `/** A catalog iconKey → its mark (apps/web/src/loop/providers/index.ts ICONS). */\n` +
    `export const MARK_FOR_ICON_KEY: Readonly<Record<string, string>> = ${JSON.stringify(byKey, null, 2)};\n\n` +
    `/** A gateway's API shape → the mark it is drawn with (SHAPE_ICONS). */\n` +
    `export const MARK_FOR_SHAPE: Readonly<Record<string, string>> = ${JSON.stringify(byShape, null, 2)};\n`,
);
console.log(`${Object.keys(marks).length} marks → ${OUT}`);
